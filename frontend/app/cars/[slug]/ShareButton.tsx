export default function ShareButton({ url, title }: ShareButtonProps) {
  const [isOpen, setIsOpen] = useState(false);
  const [copied, setCopied] = useState(false);

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(url);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      // fallback
      const el = document.createElement("textarea");
      el.value = url;
      document.body.appendChild(el);
      el.select();
      document.execCommand("copy");
      document.body.removeChild(el);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    }
  };

  const handleShare = (getUrl: (url: string, title: string) => string) => {
    window.open(getUrl(url, title), "_blank", "width=600,height=500");
  };

  return (
    <>
      {/* Share Button */}
      <button
        onClick={() => setIsOpen(true)}
        className="flex items-center gap-2 px-4 py-2 rounded-lg border border-line text-muted hover:text-ink hover:border-line transition-all duration-200 text-sm"
      >
        <svg
          xmlns="http://www.w3.org/2000/svg"
          className="w-4 h-4"
          viewBox="0 0 24 24"
          fill="none"
          stroke="currentColor"
          strokeWidth="2"
          strokeLinecap="round"
          strokeLinejoin="round"
        >
          <circle cx="18" cy="5" r="3" />
          <circle cx="6" cy="12" r="3" />
          <circle cx="18" cy="19" r="3" />
          <line x1="8.59" y1="13.51" x2="15.42" y2="17.49" />
          <line x1="15.41" y1="6.51" x2="8.59" y2="10.49" />
        </svg>
        Share
      </button>

      {/* Modal Overlay */}
      {isOpen && (
        <div
          className="fixed inset-0 z-[9999] flex items-center justify-center p-4"
          style={{ backgroundColor: "rgba(0,0,0,0.7)" }}
          onClick={() => setIsOpen(false)}
        >
          <div
            className="bg-panel border border-line rounded-2xl w-full max-w-sm p-6 relative"
            style={{
              animation: "slideUp 0.25s ease-out",
            }}
            onClick={(e) => e.stopPropagation()}
          >
            {/* Close button */}
            <button
              onClick={() => setIsOpen(false)}
              className="absolute top-4 right-4 text-muted hover:text-ink transition"
            >
              <X className="w-5 h-5" />
            </button>

            {/* Title */}
            <h3 className="text-ink font-semibold text-lg mb-1">
              Share this car
            </h3>
            <p className="text-muted text-sm mb-5 truncate">{title}</p>

            {/* Share options grid */}
            <div className="grid grid-cols-3 gap-4 mb-5">
              {shareOptions.map((option) => (
                <button
                  key={option.name}
                  onClick={() => handleShare(option.getUrl)}
                  className="flex flex-col items-center gap-2 p-3 rounded-xl hover:bg-panel transition-all duration-200 group"
                >
                  <div
                    className="w-12 h-12 rounded-full flex items-center justify-center text-white"
                    style={{ backgroundColor: option.color }}
                  >
                    {option.icon}
                  </div>
                  <span className="text-muted text-xs group-hover:text-ink transition">
                    {option.name}
                  </span>
                </button>
              ))}
            </div>

            {/* Copy link */}
            <div className="flex items-center gap-2 bg-panel border border-line rounded-lg p-3">
              <span className="text-muted text-xs truncate flex-1">
                {url}
              </span>
              <button
                onClick={handleCopy}
                className="flex items-center gap-1 text-xs font-medium px-3 py-1.5 rounded-md bg-soft text-ink hover:bg-soft transition shrink-0"
              >
                {copied ? (
                  <>
                    <Check className="w-3 h-3" />
                    Copied!
                  </>
                ) : (
                  <>
                    <Link2 className="w-3 h-3" />
                    Copy
                  </>
                )}
              </button>
            </div>
          </div>
        </div>
      )}

      <style jsx>{`
        @keyframes slideUp {
          from {
            opacity: 0;
            transform: translateY(20px) scale(0.95);
          }
          to {
            opacity: 1;
            transform: translateY(0) scale(1);
          }
        }
      `}</style>
    </>
  );
}
